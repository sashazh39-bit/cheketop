def add_para(text, bold=False, center=False, space_before=0,
             space_after=6, first_indent=True, italic=False,
             color=None):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.line_spacing_rule  = WD_LINE_SPACING.ONE_POINT_FIVE
    pf.space_before       = Pt(space_before)
    pf.space_after        = Pt(space_after)
    if first_indent and not center:
        pf.first_line_indent = Cm(1.25)
    if center:
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER

    run = p.add_run(text)
    run.font.name  = "Times New Roman"
    run.font.size  = Pt(14)
    run.font.bold  = bold
    run.font.italic = italic
    if color:
        run.font.color.rgb = RGBColor(*color)
    return p

def heading(text):
    add_para(text, bold=True, center=True,
             space_before=6, space_after=6, first_indent=False)

def subheading(text):
    add_para(text, bold=True, center=False,
             space_before=4, space_after=2, first_indent=False)

